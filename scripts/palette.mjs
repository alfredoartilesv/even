/**
 * src/ui/palette.css read from Node, so the parts of the app that are not CSS (the Android
 * window, splash screen and launcher icon) take their colors from the same palette.
 * Used by scripts/android-harden.mjs and tests/palette.test.ts.
 */
import { readFileSync } from "node:fs";
import { join } from "node:path";

export const PALETTE_PATH = join(import.meta.dirname, "../src/ui/palette.css");

/** { light, dark }: every --token in palette.css by name (without "--"); dark falls back to light. */
export function parsePalette(css) {
  const vars = (block) => Object.fromEntries([...block.matchAll(/--([\w-]+):\s*([^;]+);/g)].map((m) => [m[1], m[2].trim()]));
  const split = css.indexOf("@media (prefers-color-scheme: dark)");
  const light = vars(css.slice(0, split));
  return { light, dark: { ...light, ...vars(css.slice(split)) } };
}

export function readPalette() {
  return parsePalette(readFileSync(PALETTE_PATH, "utf8"));
}

/** The Android colors for one theme: res/values/colors.xml (light) or res/values-night/colors.xml (dark). */
export function androidColorsXml(theme) {
  const colors = {
    // The AppCompat roles Capacitor's styles.xml points at.
    colorPrimary: theme.accent,
    colorPrimaryDark: theme.bg,
    colorAccent: theme.accent,
    // The window behind the WebView and the splash screen: the page background, so a cold start
    // goes from splash to app without a white flash in dark mode.
    palette_bg: theme.bg,
    brand: theme.brand,
  };
  const rows = Object.entries(colors).map(([name, hex]) => {
    if (!/^#[0-9a-f]{6}$/i.test(hex ?? "")) throw new Error(`palette: --${name} for Android must be a #rrggbb color, got ${hex}`);
    return `    <color name="${name}">${hex.toUpperCase()}</color>`;
  });
  return `<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated from src/ui/palette.css by scripts/android-harden.mjs. -->\n<resources>\n${rows.join("\n")}\n</resources>\n`;
}

